#!/usr/bin/env python3
"""Validate and canonicalize one Syft SPDX 2.3 image SBOM.

Syft intentionally assigns a wall-clock creation time and a random document
namespace.  A release SBOM normalizes only those two fields, plus the document
name, to values derived from the already verified release identity.  Package
and relationship arrays retain the order emitted by Syft so a second scan can
detect unexpected catalog instability instead of hiding it by sorting.
"""

from __future__ import annotations

import argparse
from datetime import datetime, timezone
import json
from pathlib import Path
import re
import sys
import tempfile
from typing import Any, Iterable, List, Tuple


SPDX_VERSION = "SPDX-2.3"
SYFT_VERSION = "1.51.1"
MAX_ATTESTATION_BYTES = 16 * 1024 * 1024
CANONICAL_SOURCE = "https://github.com/AishV05/DNSResolver"
DIGEST = re.compile(r"sha256:([a-f0-9]{64})")
COMPONENTS = {"admin-api", "dns-server"}


class ContractError(ValueError):
    """Raised when an SPDX document does not satisfy the release contract."""


def fail(message: str) -> "NoReturn":
    raise SystemExit(f"SPDX normalization failed: {message}")


def reject_duplicate_keys(pairs: Iterable[Tuple[str, Any]]) -> dict[str, Any]:
    result: dict[str, Any] = {}
    for key, value in pairs:
        if key in result:
            raise ContractError(f"duplicate JSON object key: {key}")
        result[key] = value
    return result


def parse_document(raw: bytes) -> dict[str, Any]:
    if not raw:
        raise ContractError("SBOM is empty")
    try:
        text = raw.decode("utf-8")
    except UnicodeDecodeError as error:
        raise ContractError(f"SBOM is not UTF-8: {error}") from error
    try:
        document = json.loads(text, object_pairs_hook=reject_duplicate_keys)
    except (json.JSONDecodeError, ContractError) as error:
        raise ContractError(f"SBOM is not valid duplicate-free JSON: {error}") from error
    if not isinstance(document, dict):
        raise ContractError("SBOM root must be an object")
    return document


def require_nonempty_string(value: Any, context: str) -> str:
    if not isinstance(value, str) or not value.strip():
        raise ContractError(f"{context} must be a non-empty string")
    return value


def validate_inventory(document: dict[str, Any]) -> None:
    if document.get("spdxVersion") != SPDX_VERSION:
        raise ContractError(f"spdxVersion must be {SPDX_VERSION}")
    if document.get("dataLicense") != "CC0-1.0":
        raise ContractError("dataLicense must be CC0-1.0")
    if document.get("SPDXID") != "SPDXRef-DOCUMENT":
        raise ContractError("document SPDXID must be SPDXRef-DOCUMENT")
    require_nonempty_string(document.get("name"), "document name")
    require_nonempty_string(document.get("documentNamespace"), "document namespace")

    creation = document.get("creationInfo")
    if not isinstance(creation, dict):
        raise ContractError("creationInfo must be an object")
    require_nonempty_string(creation.get("created"), "creationInfo.created")
    creators = creation.get("creators")
    if not isinstance(creators, list) or not all(isinstance(item, str) for item in creators):
        raise ContractError("creationInfo.creators must be an array of strings")
    if f"Tool: syft-{SYFT_VERSION}" not in creators:
        raise ContractError(f"SBOM was not generated by Syft {SYFT_VERSION}")

    packages = document.get("packages")
    if not isinstance(packages, list) or not packages:
        raise ContractError("packages must be a non-empty array")
    package_ids: set[str] = set()
    for index, package in enumerate(packages):
        if not isinstance(package, dict):
            raise ContractError(f"package {index} must be an object")
        require_nonempty_string(package.get("name"), f"package {index} name")
        package_id = require_nonempty_string(
            package.get("SPDXID"), f"package {index} SPDXID"
        )
        if package_id in package_ids:
            raise ContractError(f"duplicate package SPDXID: {package_id}")
        package_ids.add(package_id)

    described = document.get("documentDescribes")
    has_document_describes = (
        isinstance(described, list)
        and bool(described)
        and all(isinstance(item, str) and item for item in described)
    )
    relationships = document.get("relationships")
    has_describes_relationship = False
    if isinstance(relationships, list):
        for relationship in relationships:
            if (
                isinstance(relationship, dict)
                and relationship.get("spdxElementId") == "SPDXRef-DOCUMENT"
                and relationship.get("relationshipType") == "DESCRIBES"
                and isinstance(relationship.get("relatedSpdxElement"), str)
                and relationship["relatedSpdxElement"]
            ):
                has_describes_relationship = True
                break
    if not has_document_describes and not has_describes_relationship:
        raise ContractError("document must describe at least one SPDX element")


def normalized_timestamp(commit_timestamp: int) -> str:
    if isinstance(commit_timestamp, bool) or commit_timestamp < 0:
        raise ContractError("commit timestamp must be a non-negative integer")
    try:
        return datetime.fromtimestamp(commit_timestamp, timezone.utc).strftime(
            "%Y-%m-%dT%H:%M:%SZ"
        )
    except (OverflowError, OSError, ValueError) as error:
        raise ContractError(f"commit timestamp is out of range: {error}") from error


def normalize_document(
    document: dict[str, Any],
    component: str,
    repository: str,
    digest: str,
    commit_timestamp: int,
) -> bytes:
    if component not in COMPONENTS:
        raise ContractError(f"unsupported component: {component}")
    digest_match = DIGEST.fullmatch(digest)
    if digest_match is None:
        raise ContractError("image digest must be sha256 followed by 64 lowercase hex characters")
    expected_repository = {
        "admin-api": "ghcr.io/aishv05/dns-admin-api",
        "dns-server": "ghcr.io/aishv05/dns-resolver",
    }[component]
    if repository != expected_repository:
        raise ContractError(f"unexpected repository for {component}")

    validate_inventory(document)
    document["name"] = f"{repository}@{digest}"
    document["documentNamespace"] = (
        f"{CANONICAL_SOURCE}/sbom/spdx-2.3/syft-{SYFT_VERSION}/"
        f"{component}/{digest_match.group(1)}"
    )
    document["creationInfo"]["created"] = normalized_timestamp(commit_timestamp)

    encoded = (json.dumps(document, indent=2, sort_keys=True, ensure_ascii=False) + "\n").encode(
        "utf-8"
    )
    if len(encoded) > MAX_ATTESTATION_BYTES:
        raise ContractError(
            f"normalized SBOM exceeds the {MAX_ATTESTATION_BYTES}-byte attestation limit"
        )
    return encoded


def normalize_file(
    source: Path,
    destination: Path,
    component: str,
    repository: str,
    digest: str,
    commit_timestamp: int,
) -> None:
    if not source.is_file() or source.is_symlink():
        raise ContractError("source SBOM must be a regular non-symlink file")
    if destination.exists():
        raise ContractError("destination already exists")
    document = parse_document(source.read_bytes())
    encoded = normalize_document(
        document, component, repository, digest, commit_timestamp
    )
    destination.parent.mkdir(parents=True, exist_ok=True)
    with destination.open("xb") as stream:
        stream.write(encoded)


def fixture() -> dict[str, Any]:
    return {
        "spdxVersion": SPDX_VERSION,
        "dataLicense": "CC0-1.0",
        "SPDXID": "SPDXRef-DOCUMENT",
        "name": "untrusted-runtime-name",
        "documentNamespace": "https://example.invalid/random",
        "creationInfo": {
            "created": "2026-01-01T00:00:00Z",
            "creators": ["Organization: Anchore, Inc", f"Tool: syft-{SYFT_VERSION}"],
        },
        "packages": [
            {
                "name": "example-package",
                "SPDXID": "SPDXRef-Package-example",
                "downloadLocation": "NOASSERTION",
                "filesAnalyzed": False,
                "licenseConcluded": "NOASSERTION",
                "licenseDeclared": "NOASSERTION",
                "copyrightText": "NOASSERTION",
            }
        ],
        "relationships": [
            {
                "spdxElementId": "SPDXRef-DOCUMENT",
                "relationshipType": "DESCRIBES",
                "relatedSpdxElement": "SPDXRef-Package-example",
            }
        ],
    }


def self_test() -> None:
    digest = "sha256:" + "a" * 64
    first = normalize_document(
        fixture(), "admin-api", "ghcr.io/aishv05/dns-admin-api", digest, 1_700_000_000
    )
    second = normalize_document(
        fixture(), "admin-api", "ghcr.io/aishv05/dns-admin-api", digest, 1_700_000_000
    )
    if first != second or not first.endswith(b"\n") or b"\r" in first:
        raise ContractError("canonical normalization is not deterministic")
    parsed = json.loads(first)
    if parsed["name"] != f"ghcr.io/aishv05/dns-admin-api@{digest}":
        raise ContractError("normalized document name is incorrect")

    invalid = fixture()
    invalid["packages"] = []
    try:
        normalize_document(
            invalid,
            "admin-api",
            "ghcr.io/aishv05/dns-admin-api",
            digest,
            1_700_000_000,
        )
    except ContractError:
        pass
    else:
        raise ContractError("empty package inventory unexpectedly passed")

    try:
        parse_document(b'{"a": 1, "a": 2}')
    except ContractError:
        pass
    else:
        raise ContractError("duplicate JSON keys unexpectedly passed")

    with tempfile.TemporaryDirectory() as directory:
        source = Path(directory) / "raw.json"
        destination = Path(directory) / "normalized.json"
        source.write_text(json.dumps(fixture()), encoding="utf-8")
        normalize_file(
            source,
            destination,
            "dns-server",
            "ghcr.io/aishv05/dns-resolver",
            "sha256:" + "b" * 64,
            1_700_000_000,
        )
        if not destination.is_file():
            raise ContractError("normalization did not create its output")

    print("SPDX normalization self-test passed.")


def main(argv: List[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--self-test", action="store_true")
    parser.add_argument("source", nargs="?", type=Path)
    parser.add_argument("destination", nargs="?", type=Path)
    parser.add_argument("component", nargs="?")
    parser.add_argument("repository", nargs="?")
    parser.add_argument("digest", nargs="?")
    parser.add_argument("commit_timestamp", nargs="?", type=int)
    arguments = parser.parse_args(argv)

    if arguments.self_test:
        if any(
            value is not None
            for value in (
                arguments.source,
                arguments.destination,
                arguments.component,
                arguments.repository,
                arguments.digest,
                arguments.commit_timestamp,
            )
        ):
            parser.error("--self-test does not accept positional arguments")
        self_test()
        return 0

    required = (
        arguments.source,
        arguments.destination,
        arguments.component,
        arguments.repository,
        arguments.digest,
        arguments.commit_timestamp,
    )
    if any(value is None for value in required):
        parser.error(
            "SOURCE DESTINATION COMPONENT REPOSITORY DIGEST COMMIT_TIMESTAMP are required"
        )
    try:
        normalize_file(
            arguments.source,
            arguments.destination,
            arguments.component,
            arguments.repository,
            arguments.digest,
            arguments.commit_timestamp,
        )
    except (ContractError, OSError) as error:
        fail(str(error))
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main(sys.argv[1:]))
    except ContractError as error:
        fail(str(error))
