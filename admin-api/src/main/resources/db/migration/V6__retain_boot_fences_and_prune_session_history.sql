CREATE TABLE resolver_boot_fences (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resolver_id VARCHAR(63) NOT NULL,
    boot_id VARCHAR(36) NOT NULL,
    session_generation BIGINT NOT NULL,
    first_seen_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_resolver_boot_fences_resolver
        FOREIGN KEY (resolver_id) REFERENCES resolver_instances (resolver_id),
    CONSTRAINT uk_resolver_boot_fences_boot
        UNIQUE (resolver_id, boot_id),
    CONSTRAINT uk_resolver_boot_fences_generation
        UNIQUE (resolver_id, session_generation),
    CONSTRAINT uk_resolver_boot_fences_session
        UNIQUE (resolver_id, boot_id, session_generation),
    CONSTRAINT ck_resolver_boot_fences_generation
        CHECK (session_generation >= 1)
);

INSERT INTO resolver_boot_fences (
    resolver_id,
    boot_id,
    session_generation,
    first_seen_at
)
SELECT
    resolver_id,
    boot_id,
    session_generation,
    started_at
FROM resolver_sessions;

ALTER TABLE resolver_sessions
    ADD CONSTRAINT fk_resolver_sessions_boot_fence
        FOREIGN KEY (resolver_id, boot_id, session_generation)
        REFERENCES resolver_boot_fences (
            resolver_id,
            boot_id,
            session_generation
        );

CREATE INDEX idx_resolver_sessions_retention
    ON resolver_sessions (superseded_at, session_id);

